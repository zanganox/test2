def main() -> int:
    global _FORCE_REBUILD

    parser = argparse.ArgumentParser(
        description=(
            "Leak2Path v5.3.0: deterministic ULP intelligence "
            "with incremental corpus ingestion."
        )
    )

    parser.add_argument(
        "directory",
        nargs="?",
        default=str(engine.DEFAULT_INPUT_DIR),
        help="Debe ser el directorio normalized_corpus.",
    )

    parser.add_argument(
        "target",
        nargs="?",
        help="Target domain, e.g. intercorp.com.pe",
    )

    parser.add_argument(
        "--output-dir",
        default=None,
    )

    parser.add_argument(
        "--source-type",
        default="ulp",
        choices=(
            "unknown",
            "stealer",
            "ulp",
            "breach",
            "combolist",
        ),
    )

    parser.add_argument(
        "--search-engine",
        default="auto",
        choices=(
            "auto",
            "python",
            "tgrep",
        ),
        help=(
            "auto/tgrep usa índice y fallback; "
            "python fuerza lectura completa."
        ),
    )

    parser.add_argument(
        "--tgrep-path",
        default=engine.DEFAULT_TGREP_PATH,
    )

    parser.add_argument(
        "--index-path",
        default=str(engine.DEFAULT_INDEX_DIR),
    )

    parser.add_argument(
        "--verify-index",
        action="store_true",
        help=(
            "Contrasta índice contra Full Text global; más lento."
        ),
    )

    parser.add_argument(
        "--force-rebuild",
        action="store_true",
        help=(
            "Ignora el estado previo y vuelve a analizar todos los TXT."
        ),
    )

    parser.add_argument(
        "--demo",
        action="store_true",
    )

    parser.add_argument(
        "--demo-input-dir",
        default=None,
    )

    args = parser.parse_args()

    _FORCE_REBUILD = bool(args.force_rebuild)

    if args.demo:

        if args.demo_input_dir:
            demo_dir = (
                Path(args.demo_input_dir)
                .expanduser()
                .resolve()
            )

        else:
            demo_dir = Path(
                tempfile.mkdtemp(
                    prefix="leak2path_v53_demo_"
                )
            )

        engine.make_demo_corpus(demo_dir)

        target = "acme.example"
        input_dir = demo_dir
        source_type = "unknown"
        search_engine = "python"
        tgrep_path = None
        index_dir = None
        verify_index = False

    else:

        if not args.target:
            parser.error(
                "Provide <target>, or use --demo."
            )

        input_dir = (
            Path(args.directory)
            .expanduser()
            .resolve()
        )

        target = args.target
        source_type = args.source_type
        search_engine = args.search_engine
        tgrep_path = args.tgrep_path

        index_dir = (
            Path(args.index_path)
            .expanduser()
            .resolve()
        )

        verify_index = args.verify_index

    date_tag = dt.datetime.now().strftime("%Y%m%d")

    output_dir = (
        Path(args.output_dir)
        .expanduser()
        .resolve()
        if args.output_dir
        else (
            Path.cwd()
            / f"{engine.norm_target(target)}-v{VERSION}-{date_tag}"
        ).resolve()
    )

    try:
        return _run_pipeline_v53(
            input_dir=input_dir,
            target=target,
            output_dir=output_dir,
            source_type=source_type,
            search_engine=search_engine,
            tgrep_path=tgrep_path,
            index_dir=index_dir,
            verify_index=verify_index,
            allow_demo=args.demo,
        )

    except Exception as exc:
        print(
            f"[!] Fatal error: {exc}",
            file=sys.stderr,
        )
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
