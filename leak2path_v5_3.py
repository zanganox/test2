def _append_warning(
    value: str,
    extra: str,
) -> str:
    return (value + " " if value else "") + extra


def _incremental_search_with_fallback(
    binary: Optional[str],
    input_dir: Path,
    all_files: Sequence[Path],
    pattern: str,
    matcher: Any,
    index_dir: Optional[Path],
    search_engine: str,
    fixed: bool,
    verify_index: bool,
    stage: str,
) -> Dict[str, Any]:
    """
    Search the indexed corpus, but directly scan every new/changed file.

    v5.2 returns tgrep_indexed_unverified only when it used index results
    without a Full Text comparison.

    In that specific case, matches from changed paths are discarded and
    replaced with Python results from those paths.

    Verified, Text Scan and Python fallback results already cover the
    current filesystem and therefore do not need this delta operation.
    """

    result = _ORIGINAL_SEARCH_WITH_FALLBACK(
        binary=binary,
        input_dir=input_dir,
        all_files=all_files,
        pattern=pattern,
        matcher=matcher,
        index_dir=index_dir,
        search_engine=search_engine,
        fixed=fixed,
        verify_index=verify_index,
        stage=stage,
    )

    ctx = _CONTEXT

    if not ctx or not ctx.get("enabled"):
        return result

    if result.get("engine") != "tgrep_indexed_unverified":
        return result

    changed_keys: Set[str] = ctx["changed_keys"]

    changed_paths = [
        path
        for path in all_files
        if _relative_key(path, ctx["input_dir"]) in changed_keys
    ]

    if not changed_paths:
        return result

    delta_started = time.perf_counter()

    # Remove potentially stale indexed results belonging to changed files.
    indexed_unchanged = [
        match
        for match in result.get("matches", [])
        if _relative_key(
            Path(match["path"]),
            ctx["input_dir"],
        ) not in changed_keys
    ]

    # Search the changed files directly on the current filesystem.
    delta = engine.python_search(
        changed_paths,
        matcher,
        stage + "_INCREMENTAL_DELTA",
    )

    # Stable deduplication protects against watcher/index overlap.
    merged: Dict[
        Tuple[str, int, str],
        Dict[str, Any],
    ] = {}

    for match in indexed_unchanged + delta.get("matches", []):
        key = (
            engine.normalize_path_key(str(match["path"])),
            int(match["line_number"]),
            match["line"],
        )

        merged[key] = match

    result["matches"] = list(merged.values())

    result["python_seconds"] = round(
        float(result.get("python_seconds", 0.0))
        + float(delta.get("elapsed_seconds", 0.0)),
        4,
    )

    result.setdefault("errors", []).extend(
        delta.get("errors", [])
    )

    result["engine"] = (
        "tgrep_indexed_unverified+python_delta"
    )

    result["warning"] = _append_warning(
        result.get("warning", ""),
        f"{len(changed_paths)} archivo(s) nuevo(s)/modificado(s) "
        "fueron buscados directamente con Python; se descartaron sus "
        "coincidencias indexadas para evitar datos obsoletos.",
    )

    ctx["delta_searches"].append({
        "stage": stage,
        "files_scanned": len(changed_paths),
        "matches_added": len(delta.get("matches", [])),
        "elapsed_seconds": round(
            time.perf_counter() - delta_started,
            4,
        ),
        "errors": len(delta.get("errors", [])),
    })

    print(
        f"[+] Delta {stage:<12}: "
        f"{len(changed_paths)} archivo(s), "
        f"{len(delta.get('matches', []))} coincidencia(s) Python"
    )

    return result


# Patch only the search coordinator.
# Parsing and analytics remain the v5.2.0 implementation.
engine.search_with_fallback = (
    _incremental_search_with_fallback
)


