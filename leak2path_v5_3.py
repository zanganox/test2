def _run_pipeline_v53(
    input_dir: Path,
    target: str,
    output_dir: Path,
    source_type: str,
    search_engine: str,
    tgrep_path: Optional[str],
    index_dir: Optional[Path],
    verify_index: bool,
    allow_demo: bool = False,
) -> int:

    global _CONTEXT

    # Synthetic demo uses the original engine without persistent state.
    if allow_demo:
        _CONTEXT = None

        return _ORIGINAL_RUN_PIPELINE(
            input_dir,
            target,
            output_dir,
            source_type,
            search_engine,
            tgrep_path,
            index_dir,
            verify_index,
            allow_demo=True,
        )

    input_dir = Path(input_dir).resolve()
    output_dir = Path(output_dir).resolve()

    if engine.path_is_within(output_dir, input_dir):
        raise ValueError(
            "El directorio de salida no puede estar dentro del corpus."
        )

    files, snapshot, stat_errors = _snapshot_files(
        input_dir,
        output_dir,
    )

    state_path = output_dir / STATE_FILENAME

    previous = _load_state(state_path)

    delta = _build_delta(
        input_dir,
        target,
        snapshot,
        previous,
        _FORCE_REBUILD,
    )

    delta_keys = set(delta["changed_keys"])

    _CONTEXT = {
        "enabled": True,
        "input_dir": input_dir,
        "changed_keys": delta_keys,
        "delta_searches": [],
    }

    print("\n[+] Incremental ingestion v5.3.0")
    print(f"[+] Estado                 : {delta['reason']}")
    print(f"[+] Archivos descubiertos  : {len(files)}")
    print(f"[+] Nuevos                 : {len(delta['added'])}")
    print(f"[+] Modificados            : {len(delta['modified'])}")
    print(f"[+] Eliminados             : {len(delta['deleted'])}")
    print(f"[+] Sin cambios            : {len(delta['unchanged'])}")

    if _FORCE_REBUILD:
        print(
            "[!] --force-rebuild: se analizará el corpus completo."
        )

    if verify_index:
        print(
            "[!] --verify-index realiza verificación Full Text global; "
            "puede ser más lento."
        )

    if search_engine == "python":
        print(
            "[!] --search-engine python recorre el corpus completo "
            "en cada búsqueda."
        )

    if stat_errors:
        print(
            f"[!] No se pudo obtener metadata de "
            f"{len(stat_errors)} archivo(s); no se guardará estado."
        )

    started = time.perf_counter()

    try:
        status = _ORIGINAL_RUN_PIPELINE(
            input_dir,
            target,
            output_dir,
            source_type,
            search_engine,
            tgrep_path,
            index_dir,
            verify_index,
            allow_demo=False,
        )

    finally:
        ctx = _CONTEXT
        _CONTEXT = None

    # Persist state only after a clean run.
    if status == 0 and not stat_errors:

        incremental = {
            "enabled": True,
            "version": VERSION,
            "mode": (
                "full_rebuild"
                if delta["full_rebuild"]
                else "incremental"
            ),
            "reason": delta["reason"],
            "files_discovered": len(files),
            "files_added": len(delta["added"]),
            "files_modified": len(delta["modified"]),
            "files_deleted": len(delta["deleted"]),
            "files_unchanged": len(delta["unchanged"]),
            "delta_searches": (
                ctx["delta_searches"] if ctx else []
            ),
            "inventory_errors": stat_errors,
            "inventory_signature": (
                "relative_path + size_bytes + mtime_ns + ctime_ns"
            ),
            "processing_model": (
                "tgrep index for unchanged corpus + direct Python scan "
                "for new/modified files when indexed results are "
                "unverified; global normalization, triage and outputs "
                "are rebuilt each run"
            ),
            "limitations": [
                (
                    "Metadata-based change detection; use "
                    "--force-rebuild if a file may have changed while "
                    "preserving its timestamps and size."
                ),
                (
                    "--verify-index, --search-engine python, index "
                    "fallbacks and oversized-file handling may scan "
                    "the full corpus."
                ),
                (
                    "A stable --output-dir is required to persist the "
                    "state file and HMAC key between executions."
                ),
            ],
            "run_elapsed_seconds": round(
                time.perf_counter() - started,
                3,
            ),
            "state_file": STATE_FILENAME,
        }

        _update_output_metadata(
            output_dir,
            incremental,
        )

        new_state = {
            "version": VERSION,
            "base_engine_version": BASE_VERSION,
            "target": engine.norm_target(target),
            "input_directory": str(input_dir),
            "generated_at": dt.datetime.now().isoformat(
                timespec="seconds"
            ),
            "signature_fields": [
                "size_bytes",
                "mtime_ns",
                "ctime_ns",
            ],
            "files": snapshot,
        }

        try:
            _atomic_json_write(
                state_path,
                new_state,
            )

            print(
                f"[+] Estado incremental guardado : {state_path}"
            )

        except OSError as exc:
            print(
                f"[!] No se pudo guardar el estado incremental: {exc}"
            )

    else:
        print(
            "[!] No se actualizó incremental_state.json: "
            "la ejecución terminó con errores o el inventario tuvo fallos."
        )

    return status


