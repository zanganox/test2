def _relative_key(
    path: Path,
    input_dir: Path,
) -> str:
    return (
        path.resolve()
        .relative_to(input_dir.resolve())
        .as_posix()
        .casefold()
    )


def _snapshot_files(
    input_dir: Path,
    output_dir: Path,
) -> Tuple[
    List[Path],
    Dict[str, Dict[str, int]],
    List[Dict[str, str]],
]:
    files = engine.list_txt_files(
        input_dir,
        output_dir,
    )

    snapshot: Dict[str, Dict[str, int]] = {}
    errors: List[Dict[str, str]] = []

    for path in files:
        try:
            st = path.stat()
            key = _relative_key(path, input_dir)

            snapshot[key] = {
                "size_bytes": int(st.st_size),
                "mtime_ns": int(
                    getattr(st, "st_mtime_ns", st.st_mtime * 1e9)
                ),
                "ctime_ns": int(
                    getattr(st, "st_ctime_ns", st.st_ctime * 1e9)
                ),
            }

        except (OSError, ValueError) as exc:
            errors.append({
                "path": str(path),
                "error": str(exc),
            })

    return files, snapshot, errors


def _load_state(
    path: Path,
) -> Optional[Dict[str, Any]]:
    if not path.is_file():
        return None

    try:
        with path.open("r", encoding="utf-8") as src:
            value = json.load(src)

        if (
            not isinstance(value, dict)
            or not isinstance(value.get("files"), dict)
        ):
            return None

        return value

    except (OSError, json.JSONDecodeError):
        return None


def _build_delta(
    input_dir: Path,
    target: str,
    current: Dict[str, Dict[str, int]],
    previous: Optional[Dict[str, Any]],
    force_rebuild: bool,
) -> Dict[str, Any]:

    current_keys = set(current)
    old_files = previous.get("files", {}) if previous else {}

    same_context = bool(
        previous
        and previous.get("version") == VERSION
        and previous.get("target") == engine.norm_target(target)
        and str(
            previous.get("input_directory", "")
        ).casefold() == str(
            input_dir.resolve()
        ).casefold()
    )

    if same_context:
        actual_added = sorted(
            current_keys - set(old_files)
        )

        actual_deleted = sorted(
            set(old_files) - current_keys
        )

        actual_modified = sorted(
            key
            for key in (current_keys & set(old_files))
            if current[key] != old_files.get(key)
        )

    else:
        # A different target/input root starts a new baseline.
        # Old entries are not interpreted as deleted files.
        actual_added = sorted(current_keys)
        actual_deleted = []
        actual_modified = []

    if force_rebuild:
        reason = "force_rebuild_requested"

        added = actual_added
        modified = actual_modified
        deleted = actual_deleted

        changed = set(current_keys)
        full_rebuild = True

    elif not same_context:
        reason = "first_run_or_state_context_changed"

        added = sorted(current_keys)
        modified = []
        deleted = actual_deleted

        changed = set(current_keys)
        full_rebuild = True

    else:
        reason = "incremental_change_detection"

        added = actual_added
        deleted = actual_deleted
        modified = actual_modified

        changed = set(added) | set(modified)
        full_rebuild = False

    return {
        "reason": reason,
        "full_rebuild": full_rebuild,
        "added": added,
        "modified": modified,
        "deleted": deleted,
        "unchanged": sorted(current_keys - changed),
        "changed_keys": changed,
    }


