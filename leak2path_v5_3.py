def _atomic_json_write(
    path: Path,
    value: Dict[str, Any],
) -> None:

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    fd, temp_name = tempfile.mkstemp(
        prefix=path.name + ".",
        suffix=".tmp",
        dir=str(path.parent),
    )

    try:
        with os.fdopen(
            fd,
            "w",
            encoding="utf-8",
            newline="\n",
        ) as out:

            json.dump(
                value,
                out,
                ensure_ascii=False,
                indent=2,
                sort_keys=True,
            )

            out.write("\n")

        os.replace(temp_name, path)

    except Exception:
        try:
            os.unlink(temp_name)
        except OSError:
            pass

        raise


def _update_output_metadata(
    output_dir: Path,
    incremental: Dict[str, Any],
) -> None:

    updates = (
        (
            output_dir / "search" / "search_manifest.json",
            "incremental_ingestion",
        ),
        (
            output_dir / "summary.json",
            "incremental_ingestion",
        ),
    )

    for path, key in updates:
        if not path.is_file():
            continue

        try:
            with path.open("r", encoding="utf-8") as src:
                data = json.load(src)

            data[key] = incremental

            _atomic_json_write(
                path,
                data,
            )

        except (OSError, json.JSONDecodeError) as exc:
            print(
                f"[!] No se pudo actualizar {path.name}: {exc}"
            )

    manifest_path = output_dir / "manifest.json"

    if manifest_path.is_file():
        try:
            with manifest_path.open(
                "r",
                encoding="utf-8",
            ) as src:
                data = json.load(src)

            data["incremental_state"] = STATE_FILENAME

            _atomic_json_write(
                manifest_path,
                data,
            )

        except (OSError, json.JSONDecodeError) as exc:
            print(
                f"[!] No se pudo actualizar manifest.json: {exc}"
            )


